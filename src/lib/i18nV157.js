export function setGccLanguage(value){
 locale=safeLocale(value);
 try{localStorage.setItem(STORAGE_KEY,locale);}catch{/* Browser may deny storage */}
 if(typeof document!=='undefined')document.documentElement.lang=locale;
 return locale;
}
// Managed translations track their original English source and last translated value,
// so a page can switch back to English without rebuilding or losing form inputs.
const originals=new WeakMap();
function localizedValue(node,original,value){
 const entry=originals.get(node);
 if(entry&&entry.last===value)return entry.source;
 return original;
}
function applyText(node){
 const current=node.nodeValue||'';
 const source=localizedValue(node,current,current);
 const target=translateUiText(source,locale);
 if(target!==current)node.nodeValue=target;
 originals.set(node,{source,last:target});
}
const attributes=['placeholder','aria-label','title','alt'];
const skipTags=new Set(['SCRIPT','STYLE','TEXTAREA','OPTION_UNUSED','NOSCRIPT','CODE','PRE']);
function protectedNode(el){
 return el?.closest?.('[data-i18n-skip], [contenteditable], .gcc-v104-identity, .gcc-v104-person-meta, .gcc133-detail-bio, .gcc153-status[data-user-content], .gcc122-person-name, .gcc122-person-school')||false;
}
function applyElement(el){
 if(!el||el.nodeType!==1)return;
 if(skipTags.has(el.tagName)||protectedNode(el))return;
 for(const attr of attributes){
  if(!el.hasAttribute(attr))continue;
  const key='gcc157-original-'+attr;
  const current=el.getAttribute(attr);
  let source=el.getAttribute('data-'+key);
  if(source===null){source=current;el.setAttribute('data-'+key,source);}
  else{
   const old=translateUiText(source,locale);
   if(current!==old&&current!==source){source=current;el.setAttribute('data-'+key,source);}
  }
  const target=translateUiText(source,locale);
  if(target!==current)el.setAttribute(attr,target);
 }
}
export function translateTree(root){
 if(typeof document==='undefined'||!root)return;
 if(root.nodeType===3){if(!protectedNode(root.parentElement))applyText(root);return;}
 if(root.nodeType!==1)return;
 applyElement(root);
 const walker=document.createTreeWalker(root,NodeFilter.SHOW_ELEMENT|NodeFilter.SHOW_TEXT);
 let node;
 while((node=walker.nextNode())){
  if(node.nodeType===3){
   if(!skipTags.has(node.parentElement?.tagName)&&!protectedNode(node.parentElement))applyText(node);
  }else applyElement(node);
 }
}
let observer=null,controller=null;
export function bindGccLanguage(root=document.getElementById('app'),isPublic=false){
 if(!root)return;
 observer?.disconnect();controller?.abort();
 controller=new AbortController();
 const signal=controller.signal;
 if(isPublic&&!root.querySelector('.gcc117-welcome')){
  const bar=document.createElement('div');
  bar.className='gcc157-public-lang';
  bar.setAttribute('role','group');bar.setAttribute('aria-label','Language');
  bar.innerHTML='<span aria-hidden="true">🌐</span><button type="button" data-lang="en">EN</button><button type="button" data-lang="ja">日本語</button>';
  root.append(bar);
 }
 root.querySelectorAll('[data-lang]').forEach(button=>{
  button.type='button';
  button.addEventListener('click',()=>{
   setGccLanguage(button.dataset.lang);
   refresh();
  },{signal});
 });
 function refresh(){
  document.documentElement.lang=locale;
  translateTree(root);
  for(const button of root.querySelectorAll('[data-lang]')){
   const active=button.dataset.lang===locale;
   button.setAttribute('aria-pressed',String(active));
   button.classList.toggle('gcc157-lang-active',active);
  }
  const label=root.querySelector('#current-language');
  if(label)label.textContent=locale==='ja'?'日本語':'English';
  const group=root.querySelector('.gcc157-public-lang');
  if(group)group.setAttribute('aria-label',locale==='ja'?'表示言語を選択':'Choose interface language');
 }
 refresh();
 if(typeof MutationObserver!=='undefined'){
  // Async session lists, form validation and profile cards also switch languages.
  observer=new MutationObserver(records=>{
   for(const record of records){
    if(record.type==='characterData')translateTree(record.target);
    else for(const child of record.addedNodes)if(child.nodeType===1||child.nodeType===3)translateTree(child);
   }
  });
  observer.observe(root,{subtree:true,childList:true,characterData:true});
 }
 return {refresh,dispose(){observer?.disconnect();controller?.abort();}};
}
